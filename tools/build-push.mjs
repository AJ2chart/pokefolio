// Builds supabase/functions/notify-prices/index.ts, the single file pasted into Supabase (Edge Functions → editor),
// from the tested pieces in src/: prices.js + webpush.js + core.js + main.ts. Run: node tools/build-push.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const dir = new URL('../supabase/functions/notify-prices/', import.meta.url);
const read = f => readFileSync(new URL('src/' + f, dir), 'utf8');
const strip = s => s.replace(/^import .* from '\.\/.*';\n/gm, '').replace(/^export (?=(async )?function|const|let)/gm, '');
const main = read('main.ts'), imp = main.match(/^import .*npm:.*\n/m)[0];
const out = `// GENERATED by tools/build-push.mjs from src/ — edit the files in src/, then rebuild. Do not edit by hand.\n${imp}\n` +
  ['prices.js', 'webpush.js', 'core.js'].map(f => `// ---- ${f} ----\n` + strip(read(f))).join('\n') +
  `\n// ---- main.ts ----\n` + main.replace(imp, '');
writeFileSync(new URL('index.ts', dir), out);
console.log('index.ts', out.length, 'chars');
